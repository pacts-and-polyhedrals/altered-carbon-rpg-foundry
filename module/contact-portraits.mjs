const CATEGORY_ORDER=['mercenary','supplier','informant'];
function hash(s){let h=2166136261;for(const c of String(s||''))h=Math.imul(h^c.charCodeAt(0),16777619);return h>>>0;}
export function namedPortrait(name){return CONTACT_PORTRAITS.named[String(name||'').trim().toLowerCase()]||null;}
export function contactPortrait(name,categories=''){
  const named=namedPortrait(name);if(named)return named;
  const cats=String(categories||'').toLowerCase();
  const cat=CATEGORY_ORDER.find(c=>cats.includes(c))||'contact';
  const list=CONTACT_PORTRAITS.generic[cat]||CONTACT_PORTRAITS.generic.contact;
  return list[hash(name)%list.length];
}
