const SYS='altered-carbon-rpg';
const STOCK=['icons/weapons/swords/sword-guard-steel.webp'];
export function isStockImage(img){img=String(img||'');return !img||img.startsWith('icons/svg/')||STOCK.includes(img);}
export function emblemFor(type,name){return EMBLEM_INDEX[String(type)+'|'+String(name||'').trim()]||null;}
function emblemUpdate(doc,data={}){
  const type=data.type??doc.type,name=data.name??doc.name,src=emblemFor(type,name);
  if(!src)return null;
  const update={};
  if(isStockImage(data.img??doc.img))update.img=src;
  if(doc.documentName==='Actor'){const tok=foundry.utils.getProperty(data,'prototypeToken.texture.src')??doc.prototypeToken?.texture?.src;if(isStockImage(tok))update['prototypeToken.texture.src']=src;}
  return Object.keys(update).length?update:null;
}
export function installEmblemHooks(){
  Hooks.on('preCreateItem',(doc,data)=>{try{const u=emblemUpdate(doc,data);if(u)doc.updateSource(u);}catch(error){console.warn('Altered Carbon | Emblem skipped',error);}});
  Hooks.on('preCreateActor',(doc,data)=>{try{const u=emblemUpdate(doc,data);if(u)doc.updateSource(u);}catch(error){console.warn('Altered Carbon | Emblem skipped',error);}});
}
/** GM utility: give existing world Actors/Items that still use stock icons their matching emblem. */
export async function applyEmblems({dryRun=false}={}){
  if(!game.user.isGM)return ui.notifications.warn('Only a GM can apply emblems.');
  let count=0;
  const items=game.items.contents.map(i=>({_id:i.id,...emblemUpdate(i)})).filter(u=>Object.keys(u).length>1);
  count+=items.length;if(!dryRun&&items.length)await Item.updateDocuments(items);
  const actors=game.actors.contents.map(a=>({_id:a.id,...emblemUpdate(a)})).filter(u=>Object.keys(u).length>1);
  count+=actors.length;if(!dryRun&&actors.length)await Actor.updateDocuments(actors);
  for(const actor of game.actors){const emb=actor.items.contents.map(i=>({_id:i.id,...emblemUpdate(i)})).filter(u=>Object.keys(u).length>1);count+=emb.length;if(!dryRun&&emb.length)await actor.updateEmbeddedDocuments('Item',emb);}
  ui.notifications.info(dryRun?('Altered Carbon: '+count+' documents would receive emblems.'):('Altered Carbon: applied emblems to '+count+' documents.'));
  return count;
}
